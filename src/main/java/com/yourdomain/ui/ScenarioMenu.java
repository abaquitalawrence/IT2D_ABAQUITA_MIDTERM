package com.yourdomain.ui;

import com.yourdomain.dao.ScenarioDao;
import com.yourdomain.model.ScenarioEntity;

import java.sql.SQLException;
import java.util.List;
import java.util.Scanner;

public class ScenarioMenu {
    private final ScenarioDao dao;
    private final Scanner scanner = new Scanner(System.in);

    public ScenarioMenu(ScenarioDao dao) {
        this.dao = dao;
    }

    public void run() {
        boolean running = true;
        while (running) {
            printHeader();
            System.out.println("[1] Add Delivery Order");
            System.out.println("[2] View Active Orders");
            System.out.println("[3] Exit System");
            System.out.println("==============================================");
            System.out.print("Enter choice: ");

            String choice = scanner.nextLine().trim();
            switch (choice) {
                case "1" -> addRecord();
                case "2" -> viewRecords();
                case "3" -> {
                    running = false;
                    System.out.println("\nExiting system. Thank you!");
                }
                default -> System.out.println("Invalid choice. Please enter 1, 2, or 3.");
            }

            if (running) {
                System.out.println();
                System.out.print("Press Enter to continue...");
                scanner.nextLine();
            }
        }
    }

    private void addRecord() {
        System.out.println("\n--- ADD DELIVERY ORDER ---");
        String customerName;
        while (true) {
            System.out.print("Enter Customer Name: ");
            customerName = scanner.nextLine().trim();
            if (!customerName.isBlank() && customerName.length() <= 100) {
                break;
            }
            System.out.println("Name is required and must be no more than 100 characters.");
        }

        int qty5 = readNonNegativeInt("Enter Quantity (5-gallon containers): ");
        int qty1 = readNonNegativeInt("Enter Quantity (1-gallon containers): ");

        String status;
        while (true) {
            System.out.print("Enter Status [PENDING / DELIVERING / DELIVERED]: ");
            status = scanner.nextLine().trim().toUpperCase();
            if (status.equals("PENDING") || status.equals("DELIVERING") || status.equals("DELIVERED")) {
                break;
            }
            System.out.println("Invalid status. Choose PENDING, DELIVERING, or DELIVERED.");
        }

        // orderId is generated by SQLite; zero indicates a new record.
        ScenarioEntity record = new ScenarioEntity(0, customerName, qty5, qty1, status);
        try {
            dao.addRecord(record);
            System.out.println("Delivery order added successfully.");
        } catch (SQLException e) {
            System.out.println("Could not add the record: " + e.getMessage());
        }
    }

    private int readNonNegativeInt(String prompt) {
        while (true) {
            System.out.print(prompt);
            String input = scanner.nextLine().trim();
            try {
                int value = Integer.parseInt(input);
                if (value >= 0) {
                    return value;
                }
            } catch (NumberFormatException ignored) {
                // Show a friendly validation message below.
            }
            System.out.println("Please enter a whole number that is zero or greater.");
        }
    }

    private void viewRecords() {
        System.out.println("\n--- WATER REFILLING STATION DELIVERY & ORDER REGISTRY ---");
        try {
            List<ScenarioEntity> records = dao.getAllRecords();
            if (records.isEmpty()) {
                System.out.println("No orders found.");
                return;
            }

            System.out.printf("%-5s | %-22s | %8s | %8s | %-12s%n",
                "ID", "CUSTOMER NAME", "QTY 5GAL", "QTY 1GAL", "STATUS");
            System.out.println("-------+------------------------+----------+----------+--------------");
            for (ScenarioEntity record : records) {
                System.out.printf("%-5d | %-22.22s | %8d | %8d | %-12s%n",
                    record.orderId(),
                    record.customerName(),
                    record.qty5Gallon(),
                    record.qty1Gallon(),
                    record.orderStatus());
            }
            System.out.println("Total records: " + records.size());
        } catch (SQLException e) {
            System.out.println("Could not retrieve records: " + e.getMessage());
        }
    }

    private void printHeader() {
        System.out.println("==============================================");
        System.out.println(" WATER REFILLING STATION DELIVERY & ORDER");
        System.out.println("              REGISTRY SYSTEM");
        System.out.println("==============================================");
    }
}
